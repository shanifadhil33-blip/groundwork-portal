export type TabKey = 'today' | 'requests' | 'jobs' | 'myjobs' | 'suggest' | 'chats' | 'schedule' | 'home' | 'more' | 'suggested' | 'overview';
export function tabWord(lang: string, key: TabKey, wide: boolean): string {
  const k = key === 'requests' ? 'c_requests' : wide && ['home', 'chats', 'more'].includes(key) ? `c_${key}` : key;
  const table = lang.startsWith('en') ? TAB_WORDS.en : TAB_WORDS[lang] ?? TAB_WORDS.en;
  return table[k] ?? TAB_WORDS.en[k] ?? key;
}
export function tabKey(href: string, role: string | undefined): TabKey {
  if (href === '/overview') return 'overview';
  if (href === '/dashboard' || href === '/home') return 'home';
  if (href === '/work-orders') return role === 'technician' ? 'myjobs' : role?.startsWith('client') ? 'requests' : 'jobs';
  if (href === '/schedule') return 'schedule';
  if (href === '/suggestions') return 'suggested';
  if (href === '/suggestions/new') return 'suggest';
  if (href === '/messages') return 'chats';
  return 'today';
}
